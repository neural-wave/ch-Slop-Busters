"""Collect runs/*/metrics.json into one comparison table (runs/summary.md).

  python3 ../term-generalizer/summarize.py runs/*
"""
from __future__ import annotations

import json
import sys
from pathlib import Path


def pct(x):
    return "n/a" if x is None else f"{100 * x:.1f}"


def main():
    dirs = [Path(p) for p in sys.argv[1:]] or sorted(Path("runs").glob("*"))
    rows = []
    for d in dirs:
        m_path = d / "metrics.json"
        if not m_path.exists():
            continue
        m = json.loads(m_path.read_text())
        meta = json.loads((d / "anonymize_meta.json").read_text()) if (d / "anonymize_meta.json").exists() else {}
        log = d / "anonymization_log.jsonl"
        # replayed runs (--reuse-entities) report the model time of the run they replay
        secs = [(lambda r: r.get("reused_seconds", r["seconds"]))(json.loads(line)) for line in open(log)] \
            if log.exists() else []
        p, c, i = m.get("privacy", {}), m.get("concepts", {}), m.get("icd", {})
        rows.append([
            d.name,
            pct(p.get("overall", {}).get("mention_removal")),
            pct(p.get("by_tier", {}).get("direct", {}).get("mention_removal")),
            pct(p.get("by_tier", {}).get("quasi", {}).get("mention_removal")),
            pct(p.get("name_token_removal")),
            pct(c.get("overall", {}).get("concept_recall")),
            pct(c.get("icd_relevant", {}).get("concept_recall")),
            pct(m.get("icd_terms", {}).get("mention_retention")),
            pct(i.get("anonymized", {}).get("code", {}).get("f1")),
            pct(i.get("anonymized", {}).get("category", {}).get("f1")),
            pct(i.get("agreement_f1_code")),
            i.get("coder_model", "-"),
            f"{sum(secs) / len(secs):.1f}" if secs else "-",
            meta.get("model", "-") + (f" ({meta['backend']})" if meta.get("backend") else ""),
        ])
    head = ["run", "PII removed", "direct", "quasi", "name tokens", "concept recall", "ICD-rel. concepts",
            "ICD terms kept", "ICD F1 code", "ICD F1 cat.", "agree w/ orig", "ICD coder", "s/encounter", "anonymizer"]
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] + ["---:"] * (len(head) - 2) + ["---"]) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    table = "\n".join(lines)
    out = Path("runs") / "summary.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("All numbers in %. Privacy = mention-level removal of reference PII; utility = reference medical "
                   "concept recall, and (data-only) mention retention of the encounters' ICD-10 description words and "
                   "ICD-10 F1 of a fixed zero-shot coder on the anonymized text. The reference annotation "
                   "(../term-generalizer/gold) was generated by LLM agents, not by the organizers: compare runs, do not read the "
                   "privacy and concept columns as the organizers' scores.\n\n" + table + "\n")
    print(table)


if __name__ == "__main__":
    main()
